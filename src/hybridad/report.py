"""Build docs/RESULTS.md from saved, measured outputs only (AUROC-based metrics). Missing runs are listed, never invented."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from .config import project_path, load_yaml, deep_merge
from .manifests import layout_of
from .utils import read_json

ORDER = ["A_patchcore", "B_local_st", "C_dino", "D_pc_st", "E_pc_dino", "F_three", "G_full", "H_composition",
         "G_full_mean", "G_full_or", "G_full_softmax", "G_full_identity", "G_full_compact", "C_dino_softmax",
         "C_dino_identity", "C_dino_compact", "C_dino_pool_ref", "C_dino_pool_top0.5", "C_dino_pool_top5",
         "B_local_st_top1", "B_local_st_nopenalty", "A_patchcore_reweight"]
BRANCHES = [("patchcore", "PatchCore"), ("local_st", "local ST"), ("global_attention", "DINO"),
            ("composition", "composition")]


def _f(x, nd=3):
    if isinstance(x, str):
        return x
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "n/a"
    if isinstance(x, bool):
        return "yes" if x else "no"
    if isinstance(x, (int, np.integer)):
        return str(x)
    return f"{x:.{nd}f}"


def _not_applicable(r: dict) -> list[str]:
    """Categories where every branch of the experiment is disabled by pre-registered config (e.g. composition on textures)."""
    try:
        from .pipeline import load_experiment, branch_enabled
        src = read_json(r["_dir"] / "config_used.json")["source"]
        cfg = load_experiment(src)
        return [c for c in r.get("categories_missing", [])
                if not any(branch_enabled(bc, cfg, r["_ds"], c)[0] for bc in cfg["experiment"]["branch_cfgs"].values())]
    except Exception:  # noqa: BLE001 - presentation only
        return []


NOT_RUN: list[str] = []


def collect(runs: Path) -> list[dict]:
    rows = []
    for agg in sorted(runs.glob("*/*/seed*/aggregate.json")):
        exp, ds, seed = agg.parts[-4], agg.parts[-3], agg.parts[-2]
        a = read_json(agg)
        if not a.get("categories_evaluated"):
            NOT_RUN.append(f"{exp} / {ds} / {seed}")
            continue
        a["_exp"], a["_ds"], a["_seed"], a["_dir"] = exp, ds, seed, agg.parent
        rows.append(a)
    return rows


def build(base_cfg: str | Path = "base.yaml", out: str | Path = "docs/RESULTS.md") -> Path:
    cfg = load_yaml("base.yaml")
    if str(base_cfg) != "base.yaml":
        cfg = deep_merge(cfg, load_yaml(base_cfg))   # e.g. the smoke override
    # the package's saved results by default; an explicit override config (e.g. the smoke fixture) reports its own runs
    runs = project_path(cfg["paths"]["runs"] if str(base_cfg) != "base.yaml"
                        else cfg["paths"].get("saved_runs", cfg["paths"]["runs"]))
    rows = collect(runs)
    L = ["# Results: AUROC (generated from saved outputs)", ""]
    L.append("Generated by `hybridad report`. Every number below is read from files under `runs/`; "
             "experiments or categories without saved outputs are listed as missing.")
    L.append("")
    log = runs / "TEST_ACCESS_LOG_excerpt.jsonl"
    accesses = [json.loads(l) for l in log.read_text().splitlines()] if log.exists() else []
    pre = runs / "PREREGISTRATION.json"
    L.append(f"* Pre-registration file: {'present, created ' + read_json(pre)['created_utc'] if pre.exists() else 'ABSENT'}")
    if pre.exists():
        from .prereg import code_hash
        reg, now = read_json(pre).get("code_hash"), code_hash()
        L.append(f"* The results under `runs/` were produced by the pre-registered pipeline (code hash {reg}; history "
                 "v1-v3 in runs/PREREGISTRATION_CHANGELOG.md). This package reports AUROC-based metrics only: the "
                 "pre-registered evaluation also computed threshold-dependent metrics, which are omitted here, and the "
                 f"code in this package is a derivative with that computation removed (code hash {now}), so re-running "
                 "it labels its outputs EXPLORATORY.")
    L.append(f"* Test-set evaluations recorded for the experiments in this package (runs/TEST_ACCESS_LOG_excerpt.jsonl): {len(accesses)} "
             f"({sum(1 for a in accesses if a['confirmatory'])} confirmatory, "
             f"{sum(1 for a in accesses if not a['confirmatory'])} exploratory)")
    for ds in ("mvtec_ad", "mvtec_loco"):
        ads = [a for a in accesses if a["dataset"] == ds]
        if ads:
            n_exp = sum(1 for a in ads if not a["confirmatory"])
            L.append(f"  * {ds}: {len(ads)} of them ({len(ads) - n_exp} confirmatory, {n_exp} exploratory), "
                     f"{ads[0]['utc'][:10]} to {ads[-1]['utc'][:10]} (UTC). The earlier confirmatory ones are progress "
                     "looks at the same pre-registered configurations as categories finished; the tables below come "
                     "from the latest evaluation."
                     + (" The exploratory ones are the evaluations of X3 (docs/X3.md)." if n_exp else ""))
    L.append("* Interim looks, disclosed (MVTec AD test labels joined before the final 2026-09-28 evaluation; local "
             "times, from runs/TEST_ACCESS_LOG_excerpt.jsonl): 2026-09-26 04:03-11:05, 24 evaluations during the reference "
             "phase under pre-registration v2 (before the v3 resume bug fix at 14:29); 2026-09-27 06:19-15:46, "
             "per-category G_full localization as categories finished (leather on 2026-09-28 14:52); 2026-09-27 "
             "14:47-14:48, a 13-category CPU interim evaluation of G_full, G_full_mean and A_patchcore "
             "(runs/interim/); 2026-09-27 17:57-18:10, a 14-category evaluation with leather missing for the DINO "
             "experiments (scripts/eval_ad_partial.sh). No configuration, model or fusion rule was selected, tuned or "
             "changed because of any of them. The v2->v3 change was a resume bug fix (runs/PREREGISTRATION_CHANGELOG.md), "
             "and the only later change was a runtime CUDA memory cap used to train leather's DINO, which changes neither "
             "the method nor its math (docs/METHODS.md, 'Run incidents'). The final 15-category evaluation therefore "
             "keeps its confirmatory label, with these looks stated here.")
    L.append("* Earlier, separate projects on this machine had already evaluated on the official MVTec AD and LOCO "
             "test splits (see docs/METHODS.md, 'Test-set history'); no untouched real-anomaly confirmation set exists.")
    L.append("* The post-test EXPLORATORY model X3 is described in docs/X3.md; it is NOT part of the tables below.")
    L.append("* AUROC: image-level, from continuous fused scores; 95 % CI: stratified percentile bootstrap (2,000 "
             "resamples). Pooled AUROC ranks standardized fused scores across categories (labelled secondary number).")
    L.append("")
    key = lambda r: (ORDER.index(r["_exp"]) if r["_exp"] in ORDER else 99, r["_seed"])  # noqa: E731
    all_ds = sorted({r["_ds"] for r in rows} | {"mvtec_ad", "mvtec_loco"})
    for ds in all_ds:
        dsr = sorted([r for r in rows if r["_ds"] == ds], key=key)
        if ds.startswith("synthetic"):
            L.append(f"> {ds} is the synthetic smoke fixture: code-correctness output, NOT benchmark evidence.")
            L.append("")
        L.append(f"## {ds}")
        L.append("")
        if not dsr:
            L += ["No evaluated experiments yet.", ""]
            continue
        loco = layout_of(ds) == "loco"
        head = ["experiment", "seed", "status", "categories", "macro AUROC", "pooled AUROC"]
        if loco:
            head += ["logical AUROC", "structural AUROC", "balanced mean"]
        head += [f"branch AUROC: {n}" for _, n in BRANCHES]
        L.append("| " + " | ".join(head) + " |")
        L.append("|" + "---|" * len(head))
        for r in dsr:
            st = "confirmatory" if r["evaluation_status"]["confirmatory"] else "EXPLORATORY"
            na = _not_applicable(r)
            miss = [c for c in r.get("categories_missing", []) if c not in na]
            cats = f"{len(r['categories_evaluated'])}" + (f" (missing {len(miss)})" if miss else "") + \
                   (f" ({len(na)} n/a by design)" if na else "")
            cells = [r["_exp"], r["_seed"], st, cats, _f(r.get("macro_auroc")), _f(r.get("pooled_auroc_of_fused_scores"))]
            if loco:
                cells += [_f(r.get("macro_auroc_logical")), _f(r.get("macro_auroc_structural")),
                          _f(r.get("macro_auroc_balanced_logical_structural"))]
            cells += [_f(r.get(f"macro_branch_auroc__{b}")) for b, _ in BRANCHES]
            L.append("| " + " | ".join(cells) + " |")
        L.append("")
        for r in dsr:
            if r["_exp"] != "G_full":
                continue
            cm = pd.read_csv(r["_dir"] / "category_metrics.csv")
            L.append(f"### G_full per category ({r['_seed']})")
            L.append("")
            head = ["category", "n normal", "n anomalous", "AUROC", "95% CI"]
            if loco:
                head += ["logical AUROC", "structural AUROC"]
            head += [f"branch AUROC: {n}" for _, n in BRANCHES]
            L.append("| " + " | ".join(head) + " |")
            L.append("|" + "---|" * len(head))
            for _, row in cm.iterrows():
                cells = [row["category"], _f(int(row["n_normal"])), _f(int(row["n_anomalous"])), _f(row["auroc"]),
                         f"[{_f(row['auroc_ci_lo'])}, {_f(row['auroc_ci_hi'])}]"]
                if loco:
                    cells += [_f(row["auroc_logical"]), _f(row["auroc_structural"])]
                cells += [_f(row.get(f"branch_auroc__{b}")) for b, _ in BRANCHES]
                L.append("| " + " | ".join(cells) + " |")
            L.append("")
    rep = sorted(runs.glob("R_*/*/seed*/reproduction_metrics.csv"))
    if rep:
        L.append("## Published-protocol reproductions (full official training set; AUROC)")
        L.append("")
        for p in rep:
            df = pd.read_csv(p)
            L.append(f"**{p.parts[-4]} / {p.parts[-3]}** macro image AUROC {_f(df['image_auroc'].mean())} over {len(df)} categories")
            L.append("")
    if NOT_RUN:
        L += ["## Evaluated with zero completed categories (branches not trained yet)", "",
              ", ".join(sorted(NOT_RUN)), ""]
    loc = sorted(runs.glob("*/*/*/seed*/localization.json"))
    if loc:
        L += ["## Localization (pre-registered secondary metric)", "",
              "MVTec AD: pixel AUROC and AU-PRO@0.3 (re-implementation of the official algorithm, checked against a "
              "brute-force sweep). MVTec LOCO: official MVTec evaluator v2.0, AU-sPRO (mean of logical and structural) "
              "at integration limit 0.05, run with three documented Windows compatibility shims (os.nice no-op, '/' path "
              "separators, de-duplicated initial curve points). The composition branch has no map and is excluded.", "",
              "| experiment | dataset | category | pixel AUROC | AU-PRO@0.3 | AU-sPRO@0.05 (logical / structural / mean) |",
              "|---|---|---|---|---|---|"]
        for p_ in loc:
            d = read_json(p_)
            exp_, ds_, cat_ = p_.parts[-5], p_.parts[-4], p_.parts[-3]
            sp = d.get("au_spro_by_integration_limit") or {}
            spro = (f"{_f((sp.get('logical_anomalies') or {}).get('0.05'))} / "
                    f"{_f((sp.get('structural_anomalies') or {}).get('0.05'))} / {_f(d.get('au_spro_mean_at_0.05'))}"
                    if sp else "n/a")
            L.append(f"| {exp_} | {ds_} | {cat_} | {_f(d.get('pixel_auroc'))} | {_f(d.get('au_pro_0.3'))} | {spro} |")
        L.append("")
    out = project_path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L), encoding="utf-8")
    return out
